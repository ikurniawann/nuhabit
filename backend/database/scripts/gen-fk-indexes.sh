#!/usr/bin/env bash
# Prints a delta migration that indexes every foreign key without a covering
# index. Run it against a database built only from the migrations (a fresh
# `cmd/migrate -apply`), so the output matches what the migrations produce:
#
#   DATABASE_URL=postgres://postgres@127.0.0.1:55432/scratch \
#     backend/database/scripts/gen-fk-indexes.sh \
#     > backend/database/migrations/deltas/<YYYYMMDDHHMMSS>_fk_indexes.sql
#
# An FK counts as covered when some valid index on the same table starts with
# exactly the FK columns, in any order. A partial index covers it only when
# its predicate is "<fk column> IS NOT NULL" for every FK column, because the
# lookups Postgres runs on a parent UPDATE or DELETE carry no other filter.
#
# Index names are <table>_<columns>_fk_idx. A name longer than 63 bytes, or
# one already taken in the schema, becomes its first 54 bytes, "_" and the
# first 8 hex digits of md5(full name). Output order is schema, table, columns.
# PSQL overrides the psql binary (default: psql on PATH).
set -euo pipefail

url="${1:-${DATABASE_URL:-}}"
if [[ -z "$url" ]]; then
  echo "usage: DATABASE_URL=postgres://... $0 [url]" >&2
  exit 2
fi

stmts="$("${PSQL:-psql}" "$url" -X -q -A -t -v ON_ERROR_STOP=1 <<'SQL'
WITH fk AS (
  SELECT DISTINCT ON (c.conrelid, c.conkey)
         c.conrelid, c.conkey, n.nspname, t.relname, n.oid AS nsp_oid,
         (SELECT array_agg(a.attname::text ORDER BY k.ord)
            FROM unnest(c.conkey) WITH ORDINALITY AS k(attnum, ord)
            JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum) AS cols
    FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
   WHERE c.contype = 'f'
     AND c.conparentid = 0
     AND n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast')
     AND NOT EXISTS (SELECT 1 FROM pg_depend d
                      WHERE d.classid = 'pg_class'::regclass AND d.objid = t.oid AND d.deptype = 'e')
   ORDER BY c.conrelid, c.conkey, c.conname
), uncovered AS (
  SELECT fk.* FROM fk
   WHERE NOT EXISTS (
     SELECT 1 FROM pg_index i
      WHERE i.indrelid = fk.conrelid
        AND i.indisvalid
        AND (string_to_array(i.indkey::text, ' ')::int2[])[1:cardinality(fk.conkey)] @> fk.conkey
        AND (string_to_array(i.indkey::text, ' ')::int2[])[1:cardinality(fk.conkey)] <@ fk.conkey
        AND (i.indpred IS NULL
             OR pg_get_expr(i.indpred, i.indrelid) = (
                  SELECT CASE WHEN count(*) = 1 THEN min(p) ELSE '(' || string_agg(p, ' AND ' ORDER BY ord) || ')' END
                    FROM unnest(fk.cols) WITH ORDINALITY AS u(col, ord),
                         LATERAL (SELECT '(' || quote_ident(u.col) || ' IS NOT NULL)') AS x(p)))
   )
), named AS (
  SELECT u.*, u.relname || '_' || array_to_string(u.cols, '_') || '_fk_idx' AS full_name
    FROM uncovered u
)
SELECT format('CREATE INDEX IF NOT EXISTS %I ON %I.%I (%s);',
              CASE WHEN octet_length(full_name) > 63
                     OR EXISTS (SELECT 1 FROM pg_class r WHERE r.relnamespace = nsp_oid AND r.relname = full_name)
                   THEN left(full_name, 54) || '_' || left(md5(full_name), 8)
                   ELSE full_name END,
              nspname, relname,
              (SELECT string_agg(quote_ident(col), ', ' ORDER BY ord) FROM unnest(cols) WITH ORDINALITY AS u(col, ord)))
  FROM named
 ORDER BY nspname, relname, cols;
SQL
)"

if [[ -z "$stmts" ]]; then
  echo "Every foreign key has a covering index." >&2
  exit 0
fi
count="$(printf '%s\n' "$stmts" | wc -l | tr -d ' ')"
cat <<EOF
-- Indexes for the $count foreign keys that had no covering index. Without
-- one, a DELETE or key UPDATE on the parent scans the whole child table, and
-- joins from parent to child cannot use an index.
--
-- Generated by backend/database/scripts/gen-fk-indexes.sh from the catalog
-- of a database built only from the migrations before this file. An FK
-- counts as covered when an index starts with its columns (any order), or a
-- partial index does so with only "<column> IS NOT NULL" as its predicate.
-- Names are <table>_<columns>_fk_idx; past 63 bytes, or when the name is
-- taken, they are cut to 54 bytes plus "_" and 8 hex digits of md5(full name).
--
-- CREATE INDEX takes a SHARE lock that blocks writes to its table while the
-- index builds. The runner applies this file in one transaction, so every
-- lock is held until it commits.

EOF
printf '%s\n' "$stmts"
