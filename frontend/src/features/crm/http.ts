/** Respons API CRM: `{ success, data?, error? }`. Lempar Error bila gagal. */
export async function parseCrmResponse<T>(response: Response, fallbackError: string): Promise<T> {
  const json = await response.json();
  if (!response.ok || !json.success) {
    throw new Error(json.error || fallbackError);
  }
  return json as T;
}
