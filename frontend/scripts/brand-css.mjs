#!/usr/bin/env node
// Builds src/app/brand.css from the NüHabit tokens in src/app/globals.css.
//
// The root layout loads brand.css after globals.css, with a selector that wins
// over globals.css. A build that ships a different globals.css (production
// once shipped another project's palette and fonts) still renders NüHabit.
// Self-hosted Outfit and Manrope come first in the font stacks.
//
//   node scripts/brand-css.mjs          # rewrite src/app/brand.css
//   node scripts/brand-css.mjs --check  # exit 1 when brand.css is stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

/** The text between the braces of the first block opened by `opener`. */
function block(css, opener) {
  const start = css.indexOf(opener);
  if (start < 0) throw new Error(`globals.css has no block "${opener}"`);
  let depth = 0;
  for (let i = css.indexOf("{", start); i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}" && --depth === 0) return css.slice(css.indexOf("{", start) + 1, i);
  }
  throw new Error(`unclosed block "${opener}"`);
}

/** Custom property declarations of a block, comments dropped. */
function declarations(body) {
  return body.replace(/\/\*[\s\S]*?\*\//g, "").match(/--[\w-]+\s*:[^;{}]+;/g) ?? [];
}

const SELF_HOSTED = { Outfit: "var(--font-outfit)", Manrope: "var(--font-manrope)" };

function withSelfHostedFonts(decl) {
  if (!decl.startsWith("--font")) return decl;
  return decl.replace(/"(Outfit|Manrope)"/g, (quoted, family) => `${SELF_HOSTED[family]}, ${quoted}`);
}

const indent = (decls) => decls.map((d) => `  ${withSelfHostedFonts(d)}`).join("\n");

export function buildBrandCss(globals) {
  const light = [...declarations(block(globals, "@theme {")), ...declarations(block(globals, ":root {"))];
  const dark = declarations(block(globals, '[data-theme="dark"] {'));
  const auto = declarations(block(globals, '[data-theme="auto"] {'));
  const notch = block(globals, "@utility notch {").trim();
  return `/* Generated by scripts/brand-css.mjs from globals.css. Do not edit: change
   globals.css, then run \`node scripts/brand-css.mjs\`. */

:root:root {
${indent(light)}
}

:root:root[data-theme="dark"] {
${indent(dark)}
}

@media (prefers-color-scheme: dark) {
  :root:root[data-theme="auto"] {
${indent(auto).replace(/^/gm, "  ")}
  }
}

.notch {
  ${notch}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const GLOBALS = fileURLToPath(new URL("../src/app/globals.css", import.meta.url));
  const BRAND = fileURLToPath(new URL("../src/app/brand.css", import.meta.url));
  const next = buildBrandCss(readFileSync(GLOBALS, "utf8"));
  if (process.argv.includes("--check")) {
    const current = readFileSync(BRAND, "utf8");
    if (current !== next) {
      console.error("src/app/brand.css is out of date. Run: node scripts/brand-css.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(BRAND, next);
  }
}
